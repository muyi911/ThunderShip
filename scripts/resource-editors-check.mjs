import { mockWailsBindings } from "./mock-wails-bindings.mjs";
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const require=createRequire(import.meta.url);
const {build}=require('../frontend/node_modules/esbuild');
const built=await build({plugins: [mockWailsBindings],stdin:{contents:'export {useResourceEditors} from "./src/composables/useResourceEditors"; export {ref} from "vue";',resolveDir:fileURLToPath(new URL('../frontend',import.meta.url))},bundle:true,platform:'node',format:'esm',write:false});
const {useResourceEditors,ref}=await import('data:text/javascript;base64,'+Buffer.from(built.outputFiles[0].text).toString('base64'));
const cfg=ref({servers:[],providers:[]});
const editor=useResourceEditors(cfg,ref('servers'),{task:fn=>fn(),notice:ref('')},()=>{});
const calls=[];
let respond=async()=>({ok:true,changed:false,fingerprint:'SHA256:confirmed-test-fingerprint',message:'connected'});
globalThis.window = { chrome: { webview: {} } };
globalThis.backend = {ProbeConnection:async(s,secret)=>{calls.push({s,secret});return respond();}};
editor.editServer();
editor.server.value.host='127.0.0.1';
editor.server.value.port=2222;
editor.secret.value='unsaved-password';
await editor.testConnection();
assert.equal(calls[0].s.id,'');
assert.equal(calls[0].s.port,2222);
assert.equal(calls[0].secret,'unsaved-password');
assert.equal(editor.probe.value.ok,true);
assert.equal(editor.trustDialog.value,false);
assert.equal(cfg.value.servers.length,0);
editor.server.value.port=3333;
assert.equal(editor.probe.value,null);
assert.equal(editor.trustDialog.value,false);
respond=async()=>{throw new Error('authentication failed');};
await editor.testConnection();
assert.equal(editor.probe.value.ok,false);
assert.match(editor.probe.value.message,/authentication failed/);
assert.equal(editor.testingConnection.value,false);
let finish;
respond=()=>new Promise(resolve=>{finish=resolve;});
const pending=editor.testConnection();
editor.server.value.host='other-host';
finish({ok:true,message:'stale'});
await pending;
assert.equal(editor.probe.value,null);
editor.server.value.auth='key';
assert.equal(editor.secret.value,'');
editor.server.value.keyPath='D:\\keys\\first.pem';
editor.secret.value='draft-passphrase';
respond=async()=>({ok:false,changed:false,fingerprint:'SHA256:confirmed-test-fingerprint',message:'confirm'});
await editor.testConnection();
assert.equal(editor.trustDialog.value,true);
const beforeCancel=calls.length;
editor.trustDialog.value=false;
await editor.trustHost();
assert.equal(editor.probe.value,null);
assert.equal(editor.server.value.fingerprint,'');
assert.equal(calls.length,beforeCancel);
await editor.testConnection();
assert.equal(editor.trustDialog.value,true);
respond=async()=>({ok:true,changed:false,fingerprint:'SHA256:confirmed-test-fingerprint',message:'connected'});
await editor.trustHost();
assert.equal(editor.server.value.keyPath,'D:\\keys\\first.pem');
assert.equal(editor.secret.value,'draft-passphrase');
assert.equal(editor.server.value.fingerprint,'SHA256:confirmed-test-fingerprint');
assert.equal(editor.probe.value.ok,true);
assert.equal(editor.trustDialog.value,false);
assert.equal(cfg.value.servers.length,0);
editor.probe.value={ok:false,changed:true,fingerprint:'SHA256:changed-test-fingerprint',message:'changed'};
assert.equal(editor.trustDialog.value,false);
const beforeChanged=calls.length;
await editor.trustHost();
assert.equal(calls.length,beforeChanged);
assert.equal(editor.server.value.fingerprint,'SHA256:confirmed-test-fingerprint');
editor.probe.value={ok:false,changed:false,fingerprint:'SHA256:confirmed-test-fingerprint',message:'confirm'};
assert.equal(editor.trustDialog.value,true);
editor.serverDialog.value=false;
assert.equal(editor.trustDialog.value,false);
await editor.trustHost();
assert.equal(calls.length,beforeChanged);
editor.server.value.host='third-host';
assert.equal(editor.server.value.fingerprint,'');
editor.server.value.keyPath='D:\\keys\\second.pem';
assert.equal(editor.secret.value,'');
console.log('Draft connection tests passed: trust confirmation opens automatically, cancel never trusts or reconnects, changed keys stay blocked, and stale results/credentials stay isolated.');
