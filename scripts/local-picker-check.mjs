import { mockWailsBindings } from "./mock-wails-bindings.mjs";
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const require=createRequire(import.meta.url);
const {build}=require('../frontend/node_modules/esbuild');
const built=await build({plugins: [mockWailsBindings],stdin:{contents:'export * from "./src/composables/useLocalPicker";',resolveDir:fileURLToPath(new URL('../frontend',import.meta.url))},bundle:true,platform:'node',format:'esm',write:false});
const {useLocalPicker,appendLocalFiles}=await import('data:text/javascript;base64,'+Buffer.from(built.outputFiles[0].text).toString('base64'));
const folder={name:'assets',path:'D:\\dist\\assets',directory:true,selectable:true};
const file={name:'index.html',path:'D:\\dist\\index.html',directory:false,selectable:true};
const link={name:'link',path:'D:\\dist\\link',directory:false,selectable:false};
let list=async path=>({path:path||'D:\\dist',parent:'D:\\',entries:[folder,file,link]});
let resolve=async paths=>paths.map(local=>({id:local,local}));
const received=[];
globalThis.window = { chrome: { webview: {} } };
globalThis.backend = {ListLocalDirectory:path=>list(path),ResolveLocalPaths:paths=>resolve(paths)};
const picker=useLocalPicker(files=>received.push(files));
await picker.open('D:\\dist');
picker.toggleAll();
assert.equal(picker.all.value,true);
assert.deepEqual(picker.selected.value.map(e=>e.name),['assets','index.html']);
await picker.browse(folder.path);
assert.equal(picker.selected.value.length,2,'navigation must retain batch');
resolve=async()=>{throw Error('index.html no longer exists');};
await picker.confirm();
assert.match(picker.error.value,/no longer exists/);
assert.equal(picker.opened.value,true);
assert.equal(received.length,0,'failed confirmation must not partially add');
resolve=async paths=>paths.map(local=>({id:local,local}));
await picker.confirm();
assert.equal(picker.opened.value,false);
assert.equal(received[0].length,2);
await picker.open('');
assert.equal(picker.selected.value.length,0,'new selection must not reuse cancelled checks');
picker.toggleAll();picker.toggleAll();
assert.equal(picker.selected.value.length,0);
let finish;
list=()=>new Promise(resolve=>{finish=resolve;});
const stale=picker.browse('D:\\old');
picker.close();
finish({path:'D:\\old',parent:'D:\\',entries:[]});
await stale;
assert.notEqual(picker.directory.value.path,'D:\\old');
const existing=[{id:'keep',local:'D:\\dist\\index.html',remote:'/custom/index.html'}];
appendLocalFiles(existing,[{id:'duplicate',local:'d:/DIST/index.html'},{id:'assets',local:folder.path},{id:'duplicate-folder',local:folder.path}]);
assert.equal(existing.length,2);
assert.equal(existing[0].id,'keep');
assert.equal(existing[0].remote,'/custom/index.html');
console.log('Mixed picker passed: files + folders, select all, cross-directory selection, missing inputs, cancellation, and duplicate preservation.');
