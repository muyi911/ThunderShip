import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const require=createRequire(import.meta.url);
const {build}=require('../frontend/node_modules/esbuild');
const built=await build({entryPoints:[fileURLToPath(new URL('../frontend/src/runEvents.ts',import.meta.url))],bundle:true,platform:'node',format:'esm',write:false});
const {appendRunEvents}=await import('data:text/javascript;base64,'+Buffer.from(built.outputFiles[0].text).toString('base64'));
let seq=0;
const event=(status,extra={})=>({seq:++seq,time:'2026-10-22T16:00:00+08:00',runId:'run',workflow:'workflow',server:'a',step:'upload',status,message:'',file:'/opt/app',current:0,total:100,...extra});
const rows=[];
const first=event('uploading',{current:10});
appendRunEvents(rows,[first,event('uploading',{current:20})]);
assert.equal(rows.length,1);
assert.equal(rows[0].rowId,first.seq);
assert.equal(rows[0].current,20);
assert.equal(first.current,10,'do not mutate API events');
appendRunEvents(rows,Array.from({length:1000},(_,i)=>event('uploading',{current:i/10})));
assert.equal(rows.length,1);
assert.equal(rows[0].rowId,first.seq,'keep the same DOM row across polling batches');
assert.equal(rows[0].current,99.9);
appendRunEvents(rows,[event('verified',{current:100}),event('published',{current:0,total:0})]);
assert.equal(rows.length,1);
assert.equal(rows[0].status,'published');
appendRunEvents(rows,[event('uploading',{current:1})]);
assert.equal(rows.length,2,'a later execution of the same file gets its own row');
appendRunEvents(rows,[event('uploading',{server:'b',current:2}),event('uploading',{workflow:'child',current:3}),event('uploading',{step:'other',current:4}),event('uploading',{file:'/opt/config',current:5})]);
assert.equal(rows.length,6,'parallel servers, workflows, steps and files must stay isolated');
appendRunEvents(rows,[event('failed',{file:'',message:'permission denied',total:0})]);
assert.equal(rows[0].status,'published','already published files stay successful');
assert.equal(rows[1].status,'failed');
assert.equal(rows[1].message,'permission denied');
assert.equal(rows[2].status,'uploading','another host continues');
assert.equal(rows[3].status,'uploading','another workflow continues');
assert.equal(rows[4].status,'uploading','another step continues');
assert.equal(rows[5].status,'failed');
appendRunEvents(rows,[event('cancelled',{workflow:'',server:'',step:'',file:'',message:'cancelled',total:0})]);
assert.equal(rows.some(ev=>ev.status==='uploading'),false,'run cancellation clears live progress');
const output=['line one','line two'].map(message=>event('log',{step:'command',file:'',message,total:0}));
appendRunEvents(rows,output);
assert.deepEqual(rows.slice(-2).map(ev=>ev.message),['line one','line two'],'command output stays intact');
const unknown=[];
appendRunEvents(unknown,[event('verified',{current:100}),event('unknown',{file:'',total:0,message:'publish not confirmed'})]);
assert.equal(unknown[0].status,'unknown','verification alone is not publication success');
const history=[];
appendRunEvents(history,[first,...Array.from({length:10},()=>event('uploading')),event('verified'),event('published')]);
assert.equal(history.length,1,'old saved progress logs are compacted on replay too');
assert.equal(history[0].status,'published');
const prepared=[];
appendRunEvents(prepared,[event('uploading',{current:100}),event('prepared',{current:100})]);
assert.equal(prepared.length,1,'prepared upload must update the same progress row');
assert.equal(prepared[0].status,'prepared');
appendRunEvents(prepared,[event('published',{current:0,total:0})]);
assert.equal(prepared.length,1);
assert.equal(prepared[0].status,'published');
appendRunEvents(prepared,[event('uploading'),event('prepared'),event('failed',{file:'',message:'publish denied',total:0})]);
assert.equal(prepared[0].status,'published','completed publication stays successful');
assert.equal(prepared[1].status,'failed','unpublished prepared file must reflect publication failure');
console.log('Run event checks passed: stable progress rows, parallel isolation, publication results, retries, cancellation, command output and history replay.');
