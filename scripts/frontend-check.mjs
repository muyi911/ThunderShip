import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {build}=require('../frontend/node_modules/esbuild');
const built=await build({entryPoints:[new URL('../frontend/src/flow.ts',import.meta.url).pathname.replace(/^\/([A-Za-z]:)/,'$1')],bundle:true,platform:'node',format:'esm',write:false});
const {referenceFlow,stepsFlow,canConnect,withStart,START_REF,canDeleteFrom}=await import('data:text/javascript;base64,'+Buffer.from(built.outputFiles[0].text).toString('base64'));
const leaf=id=>({mode:'',workflowId:id,children:[]});
const flow=referenceFlow({mode:'serial',workflowId:'',children:[leaf('a'),{mode:'parallel',workflowId:'',children:[leaf('b'),leaf('c')]},leaf('d')]});
const id=ref=>flow.nodes.find(n=>n.ref===ref).id;
const edge=(a,b)=>flow.edges.some(e=>e.source===id(a)&&e.target===id(b));
assert.equal(flow.nodes.length,4);
assert.ok(edge('a','b')&&edge('a','c')&&edge('b','d')&&edge('c','d'));
assert.equal(canConnect(flow,id('d'),id('a')),false);
assert.equal(canConnect(flow,id('a'),id('b')),false);
assert.equal(canConnect(flow,id('b'),id('c')),true);
const legacy=stepsFlow([{id:'first'},{id:'second'}]);
assert.deepEqual(legacy.edges,[{source:'first',target:'second'}]);
const started=withStart(legacy);
const start=started.nodes.find(n=>n.ref===START_REF);
assert.equal(started.nodes.length,3);
assert.deepEqual(started.edges[0],{source:start.id,target:'first'});
assert.equal(withStart(started),started);
assert.equal(legacy.nodes.length,2,'migration must not mutate original flow');
assert.equal(canConnect(started,'second',start.id),false);
assert.equal(canConnect(started,start.id,'second'),true,'one output must allow multiple outgoing connections');
const branched=withStart({nodes:[{id:'a',ref:'a',x:0,y:0},{id:'b',ref:'b',x:300,y:0}],edges:[]});
assert.equal(branched.edges.length,2);
globalThis.Element=class {constructor(editing){this.editing=editing;}closest(){return this.editing?this:null;}};
assert.equal(canDeleteFrom(new Element(true)),false,'editing text or dialog must not delete nodes');
assert.equal(canDeleteFrom(new Element(false)),true);
console.log('Frontend flow migration and connection checks passed.');
