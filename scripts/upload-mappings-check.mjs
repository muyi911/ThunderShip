import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const require=createRequire(import.meta.url);
const {build}=require('../frontend/node_modules/esbuild');
const built=await build({entryPoints:[fileURLToPath(new URL('../frontend/src/uploadMappings.ts',import.meta.url))],bundle:true,platform:'node',format:'esm',write:false});
const {syncUploadMappings,addUploadDirectory,uploadDestination}=await import('data:text/javascript;base64,'+Buffer.from(built.outputFiles[0].text).toString('base64'));
const asset={id:'web',files:[{id:'index',local:'D:\\dist\\index.html',kind:'file'},{id:'assets',local:'D:\\dist\\assets',kind:'folder'}]};
let files=syncUploadMappings(asset,[]);
assert.equal(files[1].includeFolder,true,'new folder mappings include the folder');
assert.equal(files[1].remote,'/opt/app');
assert.equal(uploadDestination(files[1],asset.files[1]),'/opt/app/assets');
files[0].executable=true;
const original=structuredClone(files);
files=addUploadDirectory(asset,files,'/home/work/service-b/');
assert.equal(files.length,4);
assert.deepEqual(files.slice(0,2),original);
assert.deepEqual(files.slice(2).map(f=>f.remote),['/home/work/service-b/index.html','/home/work/service-b']);
assert.equal(uploadDestination(files[3],asset.files[1]),'/home/work/service-b/assets');
assert.equal(files[2].executable,true);
assert.equal(files[3].source,'assets');
assert.equal(new Set(files.map(f=>f.id)).size,4);
assert.deepEqual(syncUploadMappings(asset,files),files,'sync must preserve every destination and mapping ID');
assert.deepEqual(addUploadDirectory(asset,files,'/home/work/service-b'),files,'repeated directory must not duplicate targets');
assert.deepEqual(addUploadDirectory(asset,[],'/').map(f=>uploadDestination(f,asset.files.find(s=>s.id===f.source))),['/index.html','/assets']);
const legacy=[{id:'old',source:'assets',remote:'/front/assets',executable:false,local:''}];
assert.deepEqual(syncUploadMappings(asset,legacy)[0],legacy[0],'old mappings keep contents-only mode');
assert.equal(addUploadDirectory({...asset,files:[asset.files[1]]},legacy,'/front').length,1,'same effective directory is not duplicated');
assert.equal(uploadDestination({...files[1],includeFolder:false,remote:'/front'},asset.files[1]),'/front');
assert.equal(uploadDestination({...files[1],remote:'/front/'},{...asset.files[1],local:'D:\\dist\\assets\\'}),'/front/assets');
for (const path of ['', 'relative', 'C:\\service', '/home/../etc', '/home//app', '/home/./app', '/home\0app']) {
  assert.throws(()=>addUploadDirectory(asset,files,path));
}
const grown={...asset,files:[...asset.files,{id:'conf',local:'D:\\config.yaml'}]};
const synchronized=syncUploadMappings(grown,files);
assert.equal(synchronized.length,5);
assert.deepEqual(synchronized.slice(0,4),files);
assert.equal(synchronized[4].source,'conf');
assert.equal(syncUploadMappings({...asset,files:[asset.files[0]]},files).length,2);
console.log('Upload mappings passed: multiple destinations, mixed assets, stable IDs, executable flags, sync, deduplication, and path validation.');
